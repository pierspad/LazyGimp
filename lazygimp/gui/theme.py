"""Design tokens — Qt port of ``lazygimp/gui/theme.py``.

Every color hex code below is copied VERBATIM from the Tk theme: this is
a toolkit swap, not a redesign. If you need to restyle the app, this is
still the one file to edit — page code (Tk or Qt) never hardcodes a
color or font tuple of its own.

Two extra things live here that the Tk version didn't need:

* ``qfont()`` — turns an ``F_*`` tuple into a ``QFont`` instance, since
  Qt widgets want font objects, not tuples, at the point of use.
* ``build_stylesheet()`` — a global QSS string applied once to the
  ``QApplication`` for chrome Qt renders itself (QScrollBar, QToolTip,
  the base QWidget palette, etc). Per-widget look (button variants, card
  borders, radii that vary per instance) is generated by
  ``lazygimp/gui/widgets.py`` itself, same division of labor as the
  Tk engine (theme.py = tokens, widgets.py = how they're used).
"""
