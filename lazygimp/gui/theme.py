def qfont(spec) -> QFont:
    """(family, size[, weight]) -> QFont. The Qt-native counterpart of
    passing an F_* tuple straight to a Tk widget's font= kwarg."""
    family, size = spec[0], spec[1]
    weight = spec[2] if len(spec) > 2 else "normal"
    f = QFont(family, size)
    f.setBold(weight == "bold")
    return f


def qcolor(hexstr: str) -> QColor:
    return QColor(hexstr)


